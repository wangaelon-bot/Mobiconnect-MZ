-- 11. FUNÇÃO DE SIMULAÇÃO DE RECARGA

CREATE OR REPLACE FUNCTION public.simulate_topup(

    p_operator TEXT,

    p_phone TEXT,

    p_amount NUMERIC

)

RETURNS UUID

LANGUAGE plpgsql

SECURITY DEFINER

SET search_path = ''

AS $$

DECLARE

    v_user_id UUID := auth.uid();

    v_balance NUMERIC(12,2);

    v_transaction_id UUID;

BEGIN

    IF v_user_id IS NULL THEN

        RAISE EXCEPTION 'Inicie sessão primeiro.';

    END IF;


    IF p_operator NOT IN (
        'Vodacom',
        'Movitel',
        'Tmcel'
    ) THEN

        RAISE EXCEPTION 'Operadora inválida.';

    END IF;


    IF p_phone !~ '^8[0-9]{8}$' THEN

        RAISE EXCEPTION 'Número inválido.';

    END IF;


    IF p_amount IS NULL
    OR p_amount <= 0
    OR p_amount <> TRUNC(p_amount) THEN

        RAISE EXCEPTION 'Valor inválido.';

    END IF;


    SELECT balance

    INTO v_balance

    FROM public.profiles

    WHERE id = v_user_id

    FOR UPDATE;


    IF v_balance IS NULL THEN

        RAISE EXCEPTION 'Perfil não encontrado.';

    END IF;


    IF v_balance < p_amount THEN

        RAISE EXCEPTION 'Saldo insuficiente.';

    END IF;


    UPDATE public.profiles

    SET balance = balance - p_amount

    WHERE id = v_user_id;


    INSERT INTO public.transactions (

        user_id,
        operator,
        phone,
        amount,
        status

    )

    VALUES (

        v_user_id,
        p_operator,
        p_phone,
        p_amount,
        'Simulada'

    )

    RETURNING id INTO v_transaction_id;


    RETURN v_transaction_id;

END;

$$;


REVOKE ALL ON FUNCTION public.simulate_topup(
    TEXT,
    TEXT,
    NUMERIC
) FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.simulate_topup(
    TEXT,
    TEXT,
    NUMERIC
) TO authenticated;


