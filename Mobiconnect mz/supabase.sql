-- 7. POLÍTICAS DE UTILIZADORES

CREATE POLICY "profile_read"

ON public.profiles

FOR SELECT

TO authenticated

USING (
    id = (SELECT auth.uid())
    OR public.is_admin()
);


-- 8. POLÍTICAS DE PACOTES

CREATE POLICY "packages_read"

ON public.packages

FOR SELECT

TO authenticated

USING (
    active = TRUE
    OR public.is_admin()
);


-- 9. POLÍTICAS DE TRANSACÇÕES

CREATE POLICY "transactions_read"

ON public.transactions

FOR SELECT

TO authenticated

USING (
    user_id = (SELECT auth.uid())
    OR public.is_admin()
);


